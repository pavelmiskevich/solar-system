import { describe, expect, it } from 'vitest';

import { snapshotFileName } from '../src/ui/snapshotButton';

/**
 * Имя файла снимка.
 *
 * Всё остальное в кнопке снимка — холст, блоб и ссылка на скачивание, то есть
 * браузер; проверяется сквозным тестом. Юнит-тестом здесь берётся то
 * единственное, что считается: имя файла по модельной дате кадра.
 */
describe('имя файла снимка', () => {
  it('составляется из модельной даты кадра', () => {
    expect(snapshotFileName(new Date('2026-08-20T15:47:00Z'))).toBe(
      'solar-system-2026-08-20-1547.png',
    );
  });

  it('дополняет числа нулями', () => {
    expect(snapshotFileName(new Date('2032-01-01T00:05:00Z'))).toBe(
      'solar-system-2032-01-01-0005.png',
    );
  });

  it('берёт дату по всемирному времени, а не по часовому поясу зрителя', () => {
    // Момент один и тот же, записан двумя способами: имя должно совпасть.
    expect(snapshotFileName(new Date('2026-08-20T23:30:00Z'))).toBe(
      snapshotFileName(new Date('2026-08-21T02:30:00+03:00')),
    );
  });

  it('не рассыпается на далёких датах', () => {
    // Время в сцене крутится до двадцати лет в секунду, и уехать в четвёртый
    // век или за десятитысячный год — дело пары минут.
    expect(snapshotFileName(new Date('0325-05-20T09:00:00Z'))).toBe(
      'solar-system-0325-05-20-0900.png',
    );
    expect(snapshotFileName(new Date('+012026-08-20T15:47:00Z'))).toBe(
      'solar-system-12026-08-20-1547.png',
    );
  });
});
