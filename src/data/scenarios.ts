import type { BodyView, SceneState } from '../core/sceneState';

/**
 * Готовые виды.
 *
 * Человек, открывший сцену впервые, не знает, что в ней искать: перед ним
 * восемь планет, полсотни тел и пустота между ними. Готовый вид за один щелчок
 * приводит туда, где интересно, — и заодно показывает, что сцена умеет больше,
 * чем возить камеру от шарика к шарику.
 *
 * Сценарий — это данные, а не код: дата, тело, расстояние в его радиусах, два
 * угла и скорость времени. Ровно то же самое лежит в адресе страницы, и это не
 * совпадение: готовый вид — это ссылка, записанная в коде.
 *
 * Даты подобраны и проверены глазами, а не вычислены. Искать подходящий момент
 * счётом — отдельная задача (поиск астрономических событий), и до неё дата
 * здесь стоит постоянная: у неё то преимущество, что вид повторяется в точности
 * и не зависит от того, когда его открыли.
 */

export interface Scenario {
  id: string;
  /** Имя в списке. */
  name: string;
  /** Одна строка о том, на что смотреть: список без неё — просто набор слов. */
  hint: string;
  /** Тело, к которому летит камера. */
  body: string;
  state: SceneState & { view: BodyView };
}

/** Сутки в секунду — с этой скоростью движение заметно, но не мельтешит. */
const DAY_PER_SECOND = 1;

/** Реальное время: там, где важно разглядеть, а не смотреть движение. */
const REAL_TIME = 1 / 86_400;

function view(body: string, radii: number, azimuth: number, elevation: number): BodyView {
  return { kind: 'body', body, radii, azimuth, elevation };
}

function stateOf(
  date: string,
  timeScale: number,
  camera: BodyView,
): SceneState & { view: BodyView } {
  return {
    jd: julianDayOf(date),
    timeScale,
    paused: false,
    view: camera,
  };
}

/** Дата строкой — в юлианскую, чтобы сценарий был готовым состоянием сцены. */
function julianDayOf(iso: string): number {
  return new Date(iso).getTime() / 86_400_000 + 2440587.5;
}

