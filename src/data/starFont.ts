/** Латинские буквы, начертанием неотличимые от русских. */
const SAME_AS: Record<string, string> = {
  A: 'А', B: 'В', C: 'С', E: 'Е', H: 'Н', K: 'К', M: 'М', O: 'О', P: 'Р', T: 'Т', X: 'Х',
};

function parse(strokes: string): Glyph {
  const points: [number, number][] = [];
  const edges: [number, number][] = [];
  const index = new Map<string, number>();

  const vertex = (x: number, y: number): number => {
    const key = `${x},${y}`;
    let at = index.get(key);
    if (at === undefined) {
      at = points.length;
      index.set(key, at);
      points.push([x / GRID, y / GRID]);
    }
    return at;
  };

  for (const stroke of strokes.split('|')) {
    const chain = stroke.trim().split(/\s+/).map((pair) => {
      const [x, y] = pair.split(',').map(Number);
      return vertex(x!, y!);
    });
    for (let i = 1; i < chain.length; i++) edges.push([chain[i - 1]!, chain[i]!]);
  }

  // Ширина - по правому краю, но не уже единичной клетки: у «!» и «I» иначе
  // соседние буквы налезали бы на них.
  const width = Math.max(1 / GRID, ...points.map(([x]) => x));
  return { width, points, edges };
}

const GLYPHS = new Map<string, Glyph>();
for (const [char, strokes] of Object.entries(STROKES)) GLYPHS.set(char, parse(strokes));
for (const [latin, cyrillic] of Object.entries(SAME_AS)) GLYPHS.set(latin, GLYPHS.get(cyrillic)!);

export const SUPPORTED = ` ${[...GLYPHS.keys()].join('')}`;

export function glyphFor(char: string): Glyph | undefined {
  return GLYPHS.get(char);
}
