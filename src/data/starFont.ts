/**
 * Звёздный шрифт: каждая буква - маленькое созвездие.
 *
 * Звёздами пишется иначе, чем пером. Буква из двадцати точек читается как
 * чертёж, а не как надпись на небе: у созвездий по четыре-семь звёзд, и
 * глаз узнаёт фигуру по немногим вершинам и линиям между ними. Поэтому
 * начертание здесь нарочно грубое - ломаные по сетке, без закруглений.
 *
 * Сетка - пять клеток в высоту, обычно три в ширину. Из неё начертание
 * переводится в доли высоты буквы, в которых работает раскладка.
 */

export interface Glyph {
  /** Ширина в долях высоты буквы. */
  readonly width: number;
  /** Вершины в долях высоты: x вправо, y вверх от строки. */
  readonly points: readonly (readonly [number, number])[];
  /** Рёбра - пары номеров вершин. */
  readonly edges: readonly (readonly [number, number])[];
}

const GRID = 5;

/** Зазор между буквами в долях высоты: меньше - слово слипается в одну фигуру. */
export const GLYPH_GAP = 0.24;

/** Ширина пробела вместе с зазорами. */
export const SPACE_ADVANCE = 0.6;

