/**
 * Геоцентрическое положение Луны в эклиптических координатах J2000, км.
 */
export function moonPositionAt(jd: number): EclipticVector {
  const T = centuriesSinceJ2000(jd);
  const T2 = T * T;
  const T3 = T2 * T;
  const T4 = T3 * T;

  // Средняя долгота Луны.
  const Lp = 218.3164477 + 481267.88123421 * T - 0.0015786 * T2 + T3 / 538841 - T4 / 65194000;
  // Среднее удлинение.
  const D = 297.8501921 + 445267.1114034 * T - 0.0018819 * T2 + T3 / 545868 - T4 / 113065000;
  // Средняя аномалия Солнца.
  const M = 357.5291092 + 35999.0502909 * T - 0.0001536 * T2 + T3 / 24490000;
  // Средняя аномалия Луны.
  const Mp = 134.9633964 + 477198.8675055 * T + 0.0087414 * T2 + T3 / 69699 - T4 / 14712000;
  // Аргумент широты.
  const F = 93.272095 + 483202.0175233 * T - 0.0036539 * T2 - T3 / 3526000 + T4 / 863310000;

  const A1 = 119.75 + 131.849 * T;
  const A2 = 53.09 + 479264.29 * T;
  const A3 = 313.45 + 481266.484 * T;

  // Поправка на убывающий эксцентриситет земной орбиты: члены с аргументом
  // Солнца ослабевают со временем.
  const E = 1 - 0.002516 * T - 0.0000074 * T2;
  const E2 = E * E;

  let sumL = 0;
  let sumR = 0;
  for (const [cD, cM, cMp, cF, al, ar] of LONGITUDE_TERMS) {
    const arg = (cD * D + cM * M + cMp * Mp + cF * F) * DEG;
    const damping = cM === 0 ? 1 : Math.abs(cM) === 1 ? E : E2;
    sumL += al * damping * Math.sin(arg);
    sumR += ar * damping * Math.cos(arg);
  }

  let sumB = 0;
  for (const [cD, cM, cMp, cF, ab] of LATITUDE_TERMS) {
    const arg = (cD * D + cM * M + cMp * Mp + cF * F) * DEG;
    const damping = cM === 0 ? 1 : Math.abs(cM) === 1 ? E : E2;
    sumB += ab * damping * Math.sin(arg);
  }

  // Дополнительные члены от действия Венеры, Юпитера и сплюснутости Земли.
  sumL += 3958 * Math.sin(A1 * DEG) + 1962 * Math.sin((Lp - F) * DEG) + 318 * Math.sin(A2 * DEG);
  sumB +=
    -2235 * Math.sin(Lp * DEG) +
    382 * Math.sin(A3 * DEG) +
    175 * Math.sin((A1 - F) * DEG) +
    175 * Math.sin((A1 + F) * DEG) +
    127 * Math.sin((Lp - Mp) * DEG) -
    115 * Math.sin((Lp + Mp) * DEG);

  // Долгота и широта отнесены к среднему равноденствию даты.
  const lambdaOfDate = Lp + sumL / 1e6;
  const beta = sumB / 1e6;
  const distance = 385000.56 + sumR / 1000;

  // Приведение к эклиптике J2000: общая прецессия по долготе. За четверть века
  // она набирает 0.37°, то есть около 2500 км на лунном расстоянии — молча
  // проигнорировать её нельзя.
  const precession = (5029.0966 * T + 1.11113 * T2 - 0.000006 * T3) / 3600;
  const lambda = (lambdaOfDate - precession) * DEG;
  const betaRad = beta * DEG;

  const cosBeta = Math.cos(betaRad);
  return {
    x: distance * cosBeta * Math.cos(lambda),
    y: distance * cosBeta * Math.sin(lambda),
    z: distance * Math.sin(betaRad),
  };
}

/** Сидерический месяц, сутки: за него Луна возвращается к тем же звёздам. */
export const SIDEREAL_MONTH = 27.321661;

/**
 * Точки орбиты Луны за один оборот от заданной даты, км.
 *
 * У спутников гигантов линия строится раз и навсегда: их эллипс в системе
 * планеты неподвижен. У Луны неподвижного эллипса нет — ряд ELP2000 считает
 * возмущённое движение, и за месяц линия не приходит ровно в начало.
 * Поэтому выборка идёт по времени и её приходится перестраивать, когда сцена
 * уходит от даты построения заметно далеко.
 */
export function sampleMoonOrbit(jd: number, segments = 180): EclipticVector[] {
  const points: EclipticVector[] = [];

  for (let s = 0; s <= segments; s += 1) {
    points.push(moonPositionAt(jd + (s / segments) * SIDEREAL_MONTH));
  }

  return points;
}
