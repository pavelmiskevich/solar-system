/**
 * Равновесная температура тела без атмосферы.
 *
 * Нужна там, где справочного числа нет и быть не может: у кометы расстояние
 * до Солнца меняется в шестьдесят раз, и одна температура на весь оборот
 * была бы верна только в одной его точке.
 *
 * Тело греется поглощённым светом и остывает собственным излучением. Свет
 * ловит сечение πR², излучает вся поверхность 4πR², и равновесие наступает
 * при S·(1 − A)·πR² = 4πR²·σT⁴, откуда T = [S·(1 − A) / (4σ)]^¼ / √r.
 * Это модель быстро вращающегося чёрного шара: тепло успевает разойтись по
 * всей поверхности, и температура на ней одна. Для ядра, делающего оборот за
 * двое суток, это честное среднее; подсолнечная точка медленного ротатора
 * была бы в √2 раз горячее.
 */

/**
 * Солнечная постоянная на 1 а.е., Вт/м².
 *
 * Номинальное значение резолюции B3 МАС 2015 года (IAU 2015 Resolution B3,
 * nominal total solar irradiance).
 */
const SOLAR_CONSTANT = 1361;

/** Постоянная Стефана - Больцмана, Вт/(м²·К⁴), CODATA 2018. */
const STEFAN_BOLTZMANN = 5.670374419e-8;

/** Ноль шкалы Цельсия в кельвинах. */
export const ZERO_CELSIUS_K = 273.15;

/**
 * Равновесная температура, К.
 *
 * Альбедо здесь болометрическое (альбедо Бонда), а в описаниях тел лежит
 * геометрическое. Для ядра кометы они близки: у тёмного тела почти всё
 * поглощается при любом из двух, и (1 − A)^¼ между 0.04 и 0.02 меняется
 * меньше чем на полпроцента - это доли кельвина на краю системы.
 *
 * Испарение льда не учтено, и это надо знать: ближе трёх а.е. оно уносит
 * часть тепла, и открытый лёд холоднее. Но у Галлеи лёд открыт на десятой
 * доле поверхности, остальное - тёмная корка, и её температуру формула даёт
 * верно. «Вега-1» в марте 1986 года, на 0.79 а.е., намерила у ядра 300-400 К
 * (Emerich et al., 1987, A&A 187, 839); формула там же даёт 310 К.
 */
export function equilibriumTemperatureK(sunDistanceAu: number, albedo: number): number {
  const atOneAu = Math.pow((SOLAR_CONSTANT * (1 - albedo)) / (4 * STEFAN_BOLTZMANN), 0.25);
  return atOneAu / Math.sqrt(sunDistanceAu);
}
