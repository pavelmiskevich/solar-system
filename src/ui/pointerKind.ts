/**
 * Чем человек указывает: пальцем или мышью.
 *
 * Нужно только тексту - подсказке внизу экрана и таблице в справке. Само
 * управление про это не спрашивает: у каждого события указателя есть свой
 * `pointerType`, и полагаться на него надёжнее, чем на устройство целиком.
 * Планшет с мышью и ноутбук с сенсорным экраном существуют, и жест на них
 * должен работать тот, которым его сделали, а не тот, которого ждали.
 */

/**
 * Сенсорный ввод - основной.
 *
 * Спрашивается не «есть ли касания», а «нет ли наведения»: касания есть и у
 * ноутбука с сенсорным экраном, но клавиатура с мышью у него тоже есть, и
 * подсказка про щипок была бы там не к месту.
 */
export function isTouchPrimary(): boolean {
  if (typeof window === 'undefined' || typeof window.matchMedia !== 'function') return false;
  return window.matchMedia('(hover: none) and (pointer: coarse)').matches;
}
