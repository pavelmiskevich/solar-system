/**
 * Единая фотометрическая шкала неба.
 *
 * Звёзды и далёкие планеты рисуются одним и тем же способом — точкой с
 * нижней границей углового размера, — и должны жить на одной шкале яркости.
 * Иначе получается ложь, которую видно сразу: Венера, ярчайший объект неба
 * после Солнца и Луны, теряется на фоне рядовых звёзд.
 *
 * Шкалой служит звёздная величина. Для звёзд она берётся из каталога, для
 * планет считается из размера, альбедо и геометрии освещения.
 */

/** Яркость точки нулевой величины на экране, до применения экспозиции. */
export const SKY_POINT_INTENSITY = 0.85;

/**
 * Радиус точки на экране по звёздной величине, пиксели.
 *
 * Глаз и матрица кодируют яркость точечного источника размером пятна, а не
 * только его светимостью, — поэтому яркие объекты и «крупнее».
 *
 * Нижняя граница — примерно пиксель, и она важнее верхней. Пятно меньше
 * пикселя растеризатор кроет частично, и от звезды остаётся доля её яркости:
 * при пределе в полпикселя небо по каталогу выглядело пустым, хотя в кадре
 * стояла тысяча звёзд, — терялись именно слабые, то есть почти все. Верхняя
 * граница в семь пикселей держит Сириус и Венеру в размерах звезды, а не
 * фонаря.
 */
export function magnitudeToPointRadius(magnitude: number): number {
  return Math.min(7, Math.max(0.95, 4.2 * Math.pow(10, -0.16 * (magnitude + 1.5))));
}

/**
 * Доля яркости точки относительно нулевой величины.
 *
 * Часть перепада яркости уже отдана размеру пятна, поэтому здесь показатель
 * меньше «физических» 0.4: при полном 10^(−0.4m) слабые звёзды исчезли бы
 * совсем, а яркие выжгли бы кадр.
 *
 * Потолок в пять единиц оставлен намеренно высоким — выше порога свечения.
 * Ярчайшие объекты неба обязаны уходить в ореол: именно этим Венера отличается
 * от рядовой звезды, и именно это теряется, если срезать шкалу на единице.
 */
export function magnitudeToBrightness(magnitude: number): number {
  return Math.min(5, Math.pow(10, -0.16 * magnitude));
}

/**
 * Абсолютная звёздная величина тела Солнечной системы (H) из диаметра и
 * геометрического альбедо. Обратная к стандартному соотношению
 * p = (1329 / D)² · 10^(−0.4·H).
 *
 * Проверка: Юпитер (D = 142984 км, p = 0.538) даёт −9.49 при справочных −9.4;
 * Венера (D = 12104 км, p = 0.689) даёт −4.39 при справочных −4.38.
 */
export function absoluteMagnitude(diameterKm: number, albedo: number): number {
  return -5 * Math.log10((diameterKm * Math.sqrt(Math.max(albedo, 1e-4))) / 1329);
}

/**
 * Видимая звёздная величина.
 *
 * @param H абсолютная величина тела
 * @param distanceToSunAu расстояние тела от Солнца
 * @param distanceToCameraAu расстояние тела от наблюдателя
 * @param phaseFactor доля освещённого диска, видимая наблюдателем, 0…1
 */
export function apparentMagnitude(
  H: number,
  distanceToSunAu: number,
  distanceToCameraAu: number,
  phaseFactor: number,
): number {
  const geometry = 5 * Math.log10(Math.max(distanceToSunAu * distanceToCameraAu, 1e-12));
  // Пол по фазе: у самого терминатора формула уходит в бесконечность, а тело
  // в реальности всё равно подсвечено рассеянием и не пропадает совсем.
  const phase = -2.5 * Math.log10(Math.max(phaseFactor, 0.015));
  return H + geometry + phase;
}
