import { AU } from '../core/units';

/**
 * Адаптация «глаза».
 *
 * Освещённость падает как 1/r², и это остаётся нетронутым: у Нептуна света
 * буквально в 900 раз меньше, чем у Земли. Компенсируем не источник, а
 * экспозицию — ровно так же, как это делает камера или зрачок.
 *
 * Компенсация намеренно неполная (показатель меньше двойки): если выровнять
 * яркость полностью, пропадёт само ощущение удаления от Солнца. Оставшийся
 * перепад читается как «здесь темнее», а не как «сцена сломалась».
 *
 * Показатель подобран по краям диапазона, а не «на глаз посередине».
 * При 1.5 на орбите Нептуна оставалось 5% земной яркости, и планета
 * превращалась в едва различимое пятно — то есть перепад переставал читаться
 * как «темнее» и начинал читаться как «ничего не видно». При 1.8 у Нептуна
 * остаётся около половины земной яркости: заметно темнее Земли, но поверхность
 * и облачные полосы разобрать можно, а это и есть смысл всей затеи.
 */
const COMPENSATION = 1.8;

/**
 * Границы экспозиции.
 *
 * Верхняя раньше стояла на 60 и срезала компенсацию как раз там, где она нужна
 * больше всего: у Нептуна требуется около 500, у Плутона — 650. Ограничение
 * при этом всё равно нужно — оно не даёт экспозиции уйти в бесконечность,
 * если камера окажется далеко за орбитой Плутона.
 */
const MIN_EXPOSURE = 0.12;
const MAX_EXPOSURE = 900;

/** Постоянная адаптации, секунды. Медленно — иначе экспозиция «дышит» на разгоне. */
const TAU = 1.5;

/**
 * Куда подтягивается яркость кадра, когда та выходит за разумные пределы.
 *
 * Ниже тёмного порога — это ночная сторона: зрачок раскрывается, и становится
 * виден пепельный свет. Выше светлого — освещённый диск во весь кадр: глаз
 * прижмуривается, и деталей в облаках Венеры не выжигает.
 */
const DARK_TARGET = 0.03;
const BRIGHT_TARGET = 1.4;

/**
 * Насколько далеко поправка по кадру может увести экспозицию от базовой.
 *
 * Границы нужны, иначе поправка съест главное свойство базовой экспозиции —
 * ощущение, что у Нептуна темнее, чем у Земли. На освещённых видах поправка
 * равна единице и ничего не меняет: у Нептуна диск даёт около половины
 * единицы яркости, то есть середину допустимого диапазона.
 *
 * Вверх — два порядка. Этого хватает, чтобы ночная сторона перестала быть
 * чёрной заливкой и проявилась пепельным светом, и не хватает, чтобы кадр
 * превратился в день: полностью вытянуть пепельный свет до дневной яркости
 * означало бы поднять над «белым» каждый освещённый вал кратера, и всё
 * изображение затопило бы свечением от них. Глаз в темноте выигрывает больше,
 * но и тратит на это минуты, а не полторы секунды.
 */
const MIN_CORRECTION = 1 / 6;
const MAX_CORRECTION = 1500;

/**
 * Ниже этой яркости кадр считается пустым. Это не «темно», а «нечего мерить»:
 * в кадре одни звёзды, а их яркость от экспозиции не зависит вовсе.
 */
const EMPTY_FRAME = 1e-7;

export class AdaptiveExposure {
  value = 1;

  private correction = 1;

  /**
   * @param distanceToSun расстояние камеры до Солнца в километрах
   * @param frameLuminance измеренная яркость кадра до экспозиции; null —
   *        в этом кадре не мерили, поправка остаётся прежней
   */
  update(dt: number, distanceToSun: number, frameLuminance: number | null = null): number {
    const au = Math.max(distanceToSun / AU, 1e-4);
    const base = clamp(Math.pow(au, COMPENSATION), MIN_EXPOSURE, MAX_EXPOSURE);

    // Пустой кадр — не повод раскрывать зрачок: в нём нечего разглядывать,
    // а звёзды экспозицию и так компенсируют.
    if (frameLuminance !== null && frameLuminance > EMPTY_FRAME) {
      // Измерение сделано без экспозиции, поэтому применяем к нему текущую:
      // именно так кадр и выглядел на экране.
      const displayed = frameLuminance * this.value;
      const ratio = clamp(displayed, DARK_TARGET, BRIGHT_TARGET) / displayed;
      this.correction = clamp(this.correction * ratio, MIN_CORRECTION, MAX_CORRECTION);
    }

    const target = clamp(base * this.correction, MIN_EXPOSURE, MAX_EXPOSURE);

    // Сглаживание в логарифме, а не в линейной шкале. Экспозиция ходит на три
    // порядка, и при линейном сглаживании первый же кадр после поворота на
    // ночную сторону поднимал её в десяток раз — рывком. В логарифме скорость
    // адаптации одинакова в ступенях яркости, на сколько бы порядков ни
    // менялась цель, и полтора десятка ступеней проходятся ровно за ту же
    // постоянную времени.
    const alpha = 1 - Math.exp(-dt / TAU);
    this.value = Math.exp(Math.log(this.value) + (Math.log(target) - Math.log(this.value)) * alpha);
    return this.value;
  }

  /** Мгновенно установить экспозицию — например, при телепорте в начало сцены. */
  reset(distanceToSun: number): void {
    const au = Math.max(distanceToSun / AU, 1e-4);
    this.correction = 1;
    this.value = clamp(Math.pow(au, COMPENSATION), MIN_EXPOSURE, MAX_EXPOSURE);
  }
}

function clamp(v: number, lo: number, hi: number): number {
  return v < lo ? lo : v > hi ? hi : v;
}
