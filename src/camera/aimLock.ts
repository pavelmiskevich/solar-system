import type { Vector3 } from 'three';

/**
 * Захват цели: тело держится в центре кадра, пока летишь свободным полётом.
 *
 * Без захвата разгон и наблюдение — взаимоисключающие занятия. Стоит тронуть
 * рули, как тело уходит из кадра: чем ближе оно, тем быстрее, — и приходится
 * выбирать между «лететь» и «смотреть». Захват снимает выбор: рулями ведут
 * камеру, а куда она смотрит, решает цель.
 *
 * Это не система отсчёта (`ReferenceFrame`) и не орбитальный режим. Отсчёт
 * тащит камеру вместе с телом и отпускает, когда до тела тысяча его радиусов;
 * орбита ведёт и положение камеры тоже. Захват не двигает камеру вовсе —
 * только поворачивает, и потому работает на любом расстоянии: Юпитер можно
 * держать в кадре и от Нептуна.
 */

export interface AimTarget {
  readonly id: string;
  /** Мировая позиция тела, км. */
  readonly worldPosition: Vector3;
}

/** Что захвату нужно от камеры: навести взгляд, остальное она сделает сама. */
export interface Aimable {
  aimAt(target: Vector3): void;
}

export class AimLock {
  private id: string | null = null;

  get targetId(): string | null {
    return this.id;
  }

  get isActive(): boolean {
    return this.id !== null;
  }

  /**
   * Захватить тело — или отпустить, если захвачено оно же.
   *
   * Другое тело именно переключает захват, а не снимает его: выбрать новую
   * цель и продолжать смотреть — одно движение, а не два.
   */
  toggle(id: string): void {
    this.id = this.id === id ? null : id;
  }

  release(): void {
    this.id = null;
  }

  /**
   * Держать цель в центре кадра. Вызывается каждый кадр до `flight.update`:
   * тот доводит взгляд до заданного направления своим сглаживанием.
   *
   * Взгляд наводится сглаженно, а не рывком. Второй сглаживатель поверх
   * первого здесь не появляется — камерой правит сам полёт, и сглаживание у
   * него одно. Зато доворот на только что захваченное тело выходит плавным,
   * а не мгновенным разворотом на сто восемьдесят градусов.
   *
   * @param target захваченное тело или null, если его не нашлось в сцене
   */
  hold(flight: Aimable, target: AimTarget | null): void {
    if (this.id === null) return;

    // Тела с таким именем в сцене нет — держаться не за что.
    if (!target || target.id !== this.id) {
      this.release();
      return;
    }

    flight.aimAt(target.worldPosition);
  }
}
